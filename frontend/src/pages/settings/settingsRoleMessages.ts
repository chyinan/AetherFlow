export type SettingsRoleMessage = keyof typeof zhCN
export function settingsRoleMessage(locale: string, key: SettingsRoleMessage, params: Record<string, string> = {}) {
  const messages = locale.startsWith('ja') ? jaJP : locale.startsWith('zh') ? zhCN : enUS
  return Object.entries(params).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, value), messages[key])
}
